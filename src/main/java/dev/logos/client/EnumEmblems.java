package dev.logos.client;

import dev.logos.graph.EnumValues.Kind;

/** Small pen drawings in the same nine-pixel grid as the existing rune emblems. */
final class EnumEmblems {
    private EnumEmblems() {}

    static String[] of(Kind kind, String value) {
        String drawing = switch (kind) {
            case MOTION -> switch (value) {
                case "forward" -> "........./.....#.../......#../#########/......#../.....#.../........./........./.........";
                case "arc" -> "........./...###.../..#+++#../.#.....#./#......#./.......##/......#.#/........./.........";
                case "homing" -> "......###/......#+#/......###/...####../..#....../.#......./.#......./.#......./.........";
                case "orbit" -> "..#####../.#+++++#./#.......#/#...#...#/#..#+#..#/#...#...#/.#.....#./..#####../.....#...";
                case "wander" -> "........./##......./..##...../....##.../...#...../..#....../...###.../......###/.........";
                default -> ".....#.../......#../..#######/.#....#../#....#.../#......../#......../.#.....#./..#####..";
            };
            case SHAPE -> switch (value) {
                case "wall" -> "#########/#++#++++#/#++#++++#/#########/#++++#++#/#++++#++#/#########/#++#++++#/#########";
                case "plane" -> "........./....#..../..##+##../##+++++##/#+++++++#/.##+++##./...###.../........./.........";
                case "disk" -> "..#####../.#+++++#./#+++++++#/#+++++++#/#+++++++#/#+++++++#/#+++++++#/.#+++++#./..#####..";
                case "dome" -> "........./...###.../..#+++#../.#++#++#./#+++#+++#/#+++#+++#/#+++#+++#/#########/.........";
                default -> "...######/..#++++##/.#++++#.#/######..#/#....#..#/#....#..#/#....#.#./#....##../######...";
            };
            case ELEMENT -> switch (value) {
                case "fire" -> "....#..../...##..../...#+#.../.#.#++#../#++#+++#./#+++++++#/#+++++++#/.#+++++#./..#####..";
                case "frost" -> "#...#...#/.#..#..#./..#.#.#../...###.../#########/...###.../..#.#.#../.#..#..#./#...#...#";
                case "lightning" -> ".....###./....###../...###.../..######./....###../...###.../..###..../.##....../.#.......";
                case "void" -> "...####../..#++#.../.#++#..../#++#...../#++#...../#++#...../.#++#..../..#++#.../...######";
                case "arcane" -> "....#..../....#..../...#+#.../..#+++#../##+++++##/..#+++#../...#+#.../....#..../....#....";
                default -> "....#..../.#..#..#./..#...#../...###.../##.#+#.##/...###.../..#...#../.#..#..#./....#....";
            };
            case WEATHER -> switch (value) {
                case "clear" -> "#...#...#/.#.....#./...###.../..#+++#../#.#+++#.#/..#+++#../...###.../.#.....#./#...#...#";
                case "rain" -> "...###.../..#+++#../##+++++#./#+++++++#/.#######./........./..#.#.#../.#.#.#.../.........";
                case "thunder" -> "...###.../..#+++#../##+++++#./#+++++++#/.#######./....##.../...##..../..###..../...#.....";
                default -> "...###.../..#+++#../##+++++#./#+++++++#/.#######./........./..+.+.+../...+.+.../..+.+.+..";
            };
            case DIMENSION -> "...###.../.##+++##./#++#++++#/#++#++++#/#+++##++#/#++++#++#/#++++#++#/.##+++##./...###...";
            case KIND -> value.equals("none") ? "..#####../.#.....#./#.#.....#/#..#....#/#...#...#/#....#..#/#.....#.#/.#.....#./..#####.." : "";
            default -> "";
        };
        return drawing.isEmpty() ? null : drawing.split("/");
    }
}
